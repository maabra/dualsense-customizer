import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.locator('#loading').waitFor({state:'hidden',timeout:60000});
if(await page.locator('.model-error').count())throw new Error(await page.locator('.model-error').textContent());
await fs.mkdir('artifacts',{recursive:true});
await page.screenshot({path:'artifacts/desktop.png'});
await page.getByRole('button',{name:'Editions',exact:true}).click();
await page.getByLabel('Search editions').fill('Wolverine');
await page.getByRole('button',{name:/Wolverine · Battle Yellow/}).click();
await page.getByRole('button',{name:'Touchpad',exact:true}).click();
await page.getByLabel('Search editions').fill('Gran Turismo');
await page.getByRole('button',{name:/Gran Turismo COLOR/}).click();
await page.getByRole('button',{name:'Face buttons',exact:true}).click();
await page.getByLabel('Search editions').fill('30th');
await page.getByRole('button',{name:/30th Anniversary/}).click();
await page.locator('#quality').click();
await page.locator('#loading').waitFor({state:'hidden',timeout:60000});
if(await page.locator('#quality').getAttribute('aria-checked')!=='true')throw new Error('High quality did not load');
await page.screenshot({path:'artifacts/mixed-high.png'});
await page.reload({waitUntil:'networkidle'});
await page.locator('#loading').waitFor({state:'hidden',timeout:60000});
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('dualsense-studio-v1')));
if(saved.parts['shell-left'].id!=='wolverine-yellow'||saved.parts.touchpad.id!=='gt'||saved.parts['button-cross'].id!=='anniversary')throw new Error('Build persistence failed');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'artifacts/mobile.png'});
await page.locator('#sheet-toggle').click();
await page.waitForTimeout(350);
await page.getByRole('button',{name:'Thumbsticks',exact:true}).click();
await page.screenshot({path:'artifacts/mobile-expanded.png'});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw new Error('Mobile horizontal overflow');
await page.setViewportSize({width:844,height:390});
await page.screenshot({path:'artifacts/mobile-landscape.png'});
if(errors.length)throw new Error(errors.join('\n'));
console.log('PASS: 3D render, edition mixing, high detail, persistence, mobile controls, no horizontal overflow, no JS errors.');
await browser.close();
